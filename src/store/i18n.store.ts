interface I18nState {
  lang: Language;
  setLang: (lang: Language) => void;
  toggleLang: () => void;
  t: (key: TranslationKey) => string;
}

export const useI18nStore = create<I18nState>((set, get) => ({
  lang: (localStorage.getItem("admin.lang") as Language) || "vi",

  setLang: (lang: Language) => {
    localStorage.setItem("admin.lang", lang);
    set({ lang });
  },

  toggleLang: () => {
    const next = get().lang === "vi" ? "en" : "vi";
    get().setLang(next);
  },

  t: (key: TranslationKey) => {
    const current = get().lang;
    return translations[current]?.[key] || translations.vi[key] || key;
  },
}));
